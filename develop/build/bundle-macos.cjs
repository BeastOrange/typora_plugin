/**
 * build/bundle-macos.cjs — 把 plugin/ 打包成单个 bundle.js（macOS 用，无 Node 运行时）
 *
 * 核心策略（与上游零冲突，便于长期同步）：
 *   1. esbuild alias 把 Node 内建模块（fs/path/os/electron…）重定向到 plugin/global/core/shims/*。
 *      上游 require("fs")/require("path")… 调用点一行不改。
 *   2. catch-all stub：任何其它无法解析的裸模块（extract-zip / zlib / child_process /
 *      tspan / onml / jquery …）替换为「按属性抛错」的占位模块，保证构建永不因缺依赖失败；
 *      命中即在运行时给出清晰、可被 LoadPlugins 捕获的错误。
 *   3. 生成静态插件注册表：esbuild 无法解析运行时的 utils.require(path, fixedName)，
 *      故扫描 plugin/ 目录，把所有 macOS 可用插件以字面量 require 写进
 *      plugin/macos-registry.generated.js，由 macos-entry.js 接管 utils.require。
 *
 * 入口：plugin/macos-entry.js（替代依赖 Electron 全局的 plugin/index.js）。
 */
const path = require("path")
const fs = require("fs")
const esbuild = require("esbuild")

const DEV_DIR = path.dirname(__dirname)
const REPO_ROOT = path.dirname(DEV_DIR)
const PLUGIN_DIR = path.join(REPO_ROOT, "plugin")
const SHIMS = path.join(PLUGIN_DIR, "global", "core", "shims")

// Node 内建 → 浏览器 shim（绝对路径，esbuild 当普通文件加载）
const ALIAS = {
  fs: path.join(SHIMS, "fs.js"),
  "fs-extra": path.join(SHIMS, "fs.js"),
  path: path.join(SHIMS, "path.js"),
  os: path.join(SHIMS, "os.js"),
  electron: path.join(SHIMS, "electron.js"),
}

// macOS 不可用插件（依赖无桥接等价物的 Node API，见 docs 审计报告）。
// 不写入注册表 → 不进入 esbuild 依赖图 → 它们的 http/selenium 等依赖也不会被解析。
const PLUGIN_BLOCKLIST = new Set([
  "ripgrep", // child_process + vscode-ripgrep
  "remote_control", // http 服务
  "article_uploader", // https + selenium-webdriver
])

const STUB_NS = "macos-stub"
const REGISTRY_FILE = path.join(PLUGIN_DIR, "macos-registry.generated.js")
const RESOURCE_MANIFEST_FILE = path.join(PLUGIN_DIR, "macos-resource-manifest.generated.js")
const ENTRY = path.join(PLUGIN_DIR, "macos-entry.js")
const OUTFILE = path.join(PLUGIN_DIR, "bundle.js")

/** 扫描出所有 base 插件名（单文件 plugin/*.js ∪ 目录 plugin/* /index.js），排除非插件目录与黑名单 */
function listBasePlugins() {
  const names = new Set()
  for (const entry of fs.readdirSync(PLUGIN_DIR, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".js")) {
      const name = entry.name.slice(0, -3)
      if (
        name === "index"
        || name === "macos-entry"
        || name === "macos-bridge-probe"
        || name === "macos-registry.generated"
        || name === "macos-resource-manifest.generated"
        || name === "bundle"
      ) continue
      names.add(name)
    } else if (entry.isDirectory()) {
      // 仅 has index.js 的目录才是插件；plugin/global、plugin/bin 等自然排除
      if (fs.existsSync(path.join(PLUGIN_DIR, entry.name, "index.js"))) names.add(entry.name)
    }
  }
  return [...names].filter(n => !PLUGIN_BLOCKLIST.has(n)).sort()
}

/** 扫描 custom 插件（plugin/custom/plugins/*），默认空 */
function listCustomPlugins() {
  const dir = path.join(PLUGIN_DIR, "custom", "plugins")
  if (!fs.existsSync(dir)) return []
  const names = new Set()
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".js")) names.add(entry.name.slice(0, -3))
    else if (entry.isDirectory() && fs.existsSync(path.join(dir, entry.name, "index.js"))) names.add(entry.name)
  }
  return [...names].sort()
}

function generateRegistry() {
  const base = listBasePlugins()
  const custom = listCustomPlugins()
  const line = (rel, name) => `  ${JSON.stringify(name)}: () => require(${JSON.stringify(rel)}),`
  const src = `// AUTO-GENERATED by develop/build/bundle-macos.cjs — DO NOT EDIT.
// macOS 静态插件注册表：esbuild 无法解析运行时 utils.require(path, fixedName)，
// 这里以字面量 require 列出全部可用插件，macos-entry.js 据此接管 utils.require。
module.exports = {
  base: {
${base.map(n => line("./" + n, n)).join("\n")}
  },
  custom: {
${custom.map(n => line("./custom/plugins/" + n, n)).join("\n")}
  },
}
`
  fs.writeFileSync(REGISTRY_FILE, src)
  console.log(`[bundle-macos] 注册表已生成：${base.length} 个 base 插件，${custom.length} 个 custom 插件`)
  return { base, custom }
}

function generateResourceManifest() {
  const manifest = {}
  const walk = (absDir, relDir) => {
    const entries = fs.readdirSync(absDir, { withFileTypes: true })
    manifest[relDir] = entries.map(entry => entry.name).sort()
    for (const entry of entries) {
      if (entry.isDirectory()) {
        walk(path.join(absDir, entry.name), path.posix.join(relDir, entry.name))
      }
    }
  }
  walk(PLUGIN_DIR, "plugin")
  fs.writeFileSync(
    RESOURCE_MANIFEST_FILE,
    `// AUTO-GENERATED by develop/build/bundle-macos.cjs — DO NOT EDIT.\nmodule.exports = ${JSON.stringify(manifest, null, 2)}\n`,
  )
  console.log(`[bundle-macos] 资源清单已生成：${Object.keys(manifest).length} 个目录`)
  return manifest
}

/** esbuild 插件：alias → shim；其余裸模块 → 抛错占位，构建永不因缺依赖失败 */
const aliasStubPlugin = {
  name: "macos-alias-stub",
  setup(build) {
    build.onResolve({ filter: /.*/ }, (args) => {
      if (args.kind === "entry-point") return
      const id = args.path
      if (id.startsWith(".") || id.startsWith("/")) return // 相对/绝对 → 正常解析
      const bare = id.startsWith("node:") ? id.slice(5) : id
      if (ALIAS[bare]) return { path: ALIAS[bare] } // → shim 文件
      return { path: id, namespace: STUB_NS } // 其它裸模块 → 占位
    })
    build.onLoad({ filter: /.*/, namespace: STUB_NS }, (args) => {
      const id = JSON.stringify(args.path)
      return {
        loader: "js",
        contents: `// macOS bundle stub for ${args.path}
const proxy = new Proxy(function () {}, {
  get(_t, prop) {
    if (prop === "__esModule") return false
    if (prop === "default") return proxy
    if (typeof prop === "symbol") return undefined
    return () => { throw new Error("[macos-stub] " + ${id} + "." + String(prop) + "() 在 macOS bundle 中不可用（无 Node 运行时）") }
  },
  apply() { throw new Error("[macos-stub] 模块 " + ${id} + " 被当作函数调用 — macOS bundle 中不可用") },
})
module.exports = proxy
`,
      }
    })
  },
}

async function build() {
  if (!fs.existsSync(ENTRY)) {
    console.error(`[bundle-macos] 入口 ${ENTRY} 不存在。`)
    process.exit(1)
  }
  generateRegistry()
  generateResourceManifest()

  const result = await esbuild.build({
    entryPoints: [ENTRY],
    bundle: true,
    outfile: OUTFILE,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: false, // 阶段二先不压缩，便于 devtools 调试
    sourcemap: true,
    metafile: true,
    plugins: [aliasStubPlugin],
    loader: { ".json": "json", ".node": "empty", ".css": "text", ".html": "text" },
    define: { "process.env.NODE_ENV": '"production"' },
    // 在所有模块之前建立 global/process（WKWebView 无 Node 全局），上游 global.xxx 才能工作
    banner: {
      js: "(function(){var g=typeof globalThis!=='undefined'?globalThis:(typeof window!=='undefined'?window:this);"
        + "if(typeof g.global==='undefined')g.global=g;"
        + "if(typeof g.process==='undefined')g.process={env:{},versions:{},platform:'darwin'};})();",
    },
    logLevel: "info",
  })

  const size = (fs.statSync(OUTFILE).size / 1024).toFixed(1)
  console.log(`[bundle-macos] ✓ 产出 ${OUTFILE} (${size} KB)`)
  if (result.metafile) {
    fs.writeFileSync(path.join(PLUGIN_DIR, "bundle.meta.json"), JSON.stringify(result.metafile, null, 2))
  }
  return result
}

build().catch((e) => {
  console.error("[bundle-macos] 构建失败:\n", e.message || e)
  process.exit(1)
})
